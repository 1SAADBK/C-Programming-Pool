int	ft_atoi(char *str)
{
	int	i;
	int	j;
	int	k;

	j = 1;
	i = 0;
	k = 0;
	while (str[i] 
		&& (str[i] == '\t' || str[i] == '\n' 
			|| str[i] == '\v' || str[i] == '\f' 
			|| str[i] == '\r' || str[i] == ' '))
		i++;
	while (str[i] && (str[i] == '+' || str[i] == '-'))
	{
		if (str[i] == '-')
			j = -j;
		i++;
	}
	while (str[i] && str[i] >= '0' && str[i] <= '9')
	{
		k = k * 10 + (str[i] - '0');
		i++;
	}
	k = j * k;
	return (k);
}
